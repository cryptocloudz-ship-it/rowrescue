import {
  pgTable,
  text,
  integer,
  boolean,
  timestamp,
  date,
  index,
  uniqueIndex,
} from "drizzle-orm/pg-core";

// ─── Users ───────────────────────────────────────────────────────────────────
export const users = pgTable(
  "users",
  {
    id: text("id").primaryKey(), // Clerk user ID
    email: text("email").notNull(),
    name: text("name"),
    stripeCustomerId: text("stripe_customer_id"),
    plan: text("plan", { enum: ["free", "pro", "team"] })
      .notNull()
      .default("free"),
    subscriptionStatus: text("subscription_status", {
      enum: ["active", "past_due", "canceled", "trialing", "incomplete"],
    }),
    stripeSubscriptionId: text("stripe_subscription_id"),
    currentPeriodEnd: timestamp("current_period_end"),
    exportsToday: integer("exports_today").notNull().default(0),
    exportsResetDate: date("exports_reset_date")
      .notNull()
      .defaultNow(),
    teamId: text("team_id"),
    teamRole: text("team_role", { enum: ["admin", "member"] }),
    createdAt: timestamp("created_at").notNull().defaultNow(),
    updatedAt: timestamp("updated_at").notNull().defaultNow(),
  },
  (table) => [index("users_email_idx").on(table.email)]
);

// ─── Teams ───────────────────────────────────────────────────────────────────
export const teams = pgTable(
  "teams",
  {
    id: text("id").primaryKey(), // UUID generated by app
    name: text("name").notNull(),
    ownerId: text("owner_id")
      .notNull()
      .references(() => users.id),
    stripeSubscriptionId: text("stripe_subscription_id"),
    seatCount: integer("seat_count").notNull().default(1),
    createdAt: timestamp("created_at").notNull().defaultNow(),
    updatedAt: timestamp("updated_at").notNull().defaultNow(),
  },
  // One team per owner: a repeat Team checkout reuses it
  (table) => [uniqueIndex("teams_owner_id_idx").on(table.ownerId)]
);

// ─── Team Invites ────────────────────────────────────────────────────────────
// Pending invites only: accepting or revoking deletes the row. Each one holds a seat.
export const teamInvites = pgTable(
  "team_invites",
  {
    id: text("id").primaryKey(),
    teamId: text("team_id")
      .notNull()
      .references(() => teams.id),
    email: text("email").notNull(), // lowercased
    token: text("token").notNull(),
    invitedBy: text("invited_by")
      .notNull()
      .references(() => users.id),
    createdAt: timestamp("created_at").notNull().defaultNow(),
  },
  (table) => [
    uniqueIndex("team_invites_team_email_idx").on(table.teamId, table.email),
    uniqueIndex("team_invites_token_idx").on(table.token),
    index("team_invites_email_idx").on(table.email),
  ]
);

// ─── Presets ─────────────────────────────────────────────────────────────────
export const presets = pgTable(
  "presets",
  {
    id: text("id").primaryKey(), // UUID generated by app
    userId: text("user_id")
      .notNull()
      .references(() => users.id),
    teamId: text("team_id").references(() => teams.id),
    name: text("name").notNull(),
    description: text("description").notNull().default(""),
    rules: text("rules").notNull(), // JSON string
    isShared: boolean("is_shared").notNull().default(false),
    createdAt: timestamp("created_at").notNull().defaultNow(),
    updatedAt: timestamp("updated_at").notNull().defaultNow(),
  },
  (table) => [
    index("presets_user_id_idx").on(table.userId),
    index("presets_team_id_idx").on(table.teamId),
  ]
);

// ─── Audit Logs ──────────────────────────────────────────────────────────────
export const auditLogs = pgTable(
  "audit_logs",
  {
    id: text("id").primaryKey(),
    teamId: text("team_id")
      .notNull()
      .references(() => teams.id),
    userId: text("user_id")
      .notNull()
      .references(() => users.id),
    action: text("action").notNull(),
    presetId: text("preset_id"),
    metadata: text("metadata"), // JSON — NO file contents
    createdAt: timestamp("created_at").notNull().defaultNow(),
  },
  (table) => [index("audit_logs_team_id_idx").on(table.teamId)]
);

// ─── Export Logs ─────────────────────────────────────────────────────────────
export const exportLogs = pgTable(
  "export_logs",
  {
    id: text("id").primaryKey(),
    userId: text("user_id")
      .notNull()
      .references(() => users.id),
    fileName: text("file_name").notNull(), // Name only, no contents
    rowCount: integer("row_count").notNull(),
    rulesApplied: text("rules_applied").notNull(), // JSON array of rule IDs
    exportedAt: timestamp("exported_at").notNull().defaultNow(),
  },
  (table) => [index("export_logs_user_id_idx").on(table.userId)]
);
